// Targets differing only by case are one file on the case-insensitive filesystem the
// fleet authors on and two on the case-sensitive one CI renders on. Refusing in both
// places keeps a repo's render portable, and the message names each target since the
// dirs alone would read as two identical strings colliding.
func TestRenderRefusesCaseFoldedTargetCollision(t *testing.T) {
	repo(t)
	write(t, ".claude/fragments/notes.md/layout.toml", "fragments = [\"base\"]\n")
	write(t, ".claude/fragments/notes.md/base.fragment.md", "# a\n")
	write(t, ".claude/fragments/upper/layout.toml", "target = \"NOTES.md\"\n\nfragments = [\"base\"]\n")
	write(t, ".claude/fragments/upper/base.fragment.md", "# b\n")

	code, _, errout := exec("render")
	if code != 2 || !strings.Contains(errout, "is shared by") {
		t.Fatalf("case-folded collision must refuse: code=%d err=%q", code, errout)
	}
	for _, want := range []string{
		"NOTES.md (.claude/fragments/upper)",
		"notes.md (.claude/fragments/notes.md)",
		// Without the reason, a reader on case-sensitive Linux — where this layout
		// genuinely works — reads the refusal as a tool bug.
		"differing only by case: one file where authoring happens, two where CI renders",
	} {
		if !strings.Contains(errout, want) {
			t.Fatalf("message must name each target and the reason, missing %q:\n%s", want, errout)
		}
	}
}

// A same-case collision is the ordinary kind: it names the dirs and stays silent about
// case, which would only be noise.
func TestRenderSameCaseCollisionOmitsCaseReason(t *testing.T) {
	repo(t)
	write(t, ".claude/fragments/notes.md/layout.toml", "fragments = [\"base\"]\n")
	write(t, ".claude/fragments/notes.md/base.fragment.md", "# a\n")
	write(t, ".claude/fragments/other/layout.toml", "target = \"notes.md\"\n\nfragments = [\"base\"]\n")
	write(t, ".claude/fragments/other/base.fragment.md", "# b\n")

	code, _, errout := exec("render")
	if code != 2 || !strings.Contains(errout, `target "notes.md" is shared by .claude/fragments/notes.md, .claude/fragments/other`) {
		t.Fatalf("same-case collision: code=%d err=%q", code, errout)
	}
	if strings.Contains(errout, "differing only by case") {
		t.Fatalf("a same-case collision must not blame case:\n%s", errout)
	}
}

// An unreadable target (here a directory in the artifact's place) is a hard error
// in the preflight, never treated as absent — otherwise the lock would register it
// and a later retry would clobber it without --force.
func TestRenderUnreadableTargetErrorsBeforeLock(t *testing.T) {
	repo(t)
	write(t, ".claude/fragments/.claude/settings.json/layout.toml", "fragments = [\"base\"]\n")
	write(t, ".claude/fragments/.claude/settings.json/base.fragment.json", "{\n  \"model\": \"opus\"\n}\n")
	if err := os.MkdirAll(".claude/settings.json", 0o750); err != nil {
		t.Fatal(err)
	}
	if code, _, errout := exec("render"); code != 2 {
		t.Fatalf("unreadable target must be a hard error: code=%d err=%s", code, errout)
	}
	if _, err := os.Stat(".claude/fragments/cc-guides.lock"); !os.IsNotExist(err) {
		t.Fatal("a preflight failure must not write the lock (which would register the target)")
	}
}

// Two dirs whose effective targets collide — one path-derived, one from a `target`
// override — are refused in the preflight, before any artifact or lock is written.
func TestRenderTargetCollisionRefusedBeforeWrite(t *testing.T) {
	repo(t)
	write(t, ".claude/fragments/.gitignore/layout.toml", "fragments = [\"base\"]\n")
	write(t, ".claude/fragments/.gitignore/base.fragment.gitignore", "node_modules/\n")
	write(t, ".claude/fragments/gitignore/layout.toml", "target = \".gitignore\"\n\nfragments = [\"logs\"]\n")
	write(t, ".claude/fragments/gitignore/logs.fragment.gitignore", "*.log\n")

	code, _, errout := exec("render")
	if code != 2 || !strings.Contains(errout, `target ".gitignore" is shared by`) {
		t.Fatalf("colliding targets: code=%d err=%q", code, errout)
	}
	if _, err := os.Stat(".gitignore"); !os.IsNotExist(err) {
		t.Fatal("a refused batch must write no artifact")
	}
	if _, err := os.Stat(".claude/fragments/cc-guides.lock"); !os.IsNotExist(err) {
		t.Fatal("a refused batch must write no lock")
	}
}

// A path-scoped render is surgical: it merges into the lock, preserving artifacts
// it did not render (unlike a full render, which rebuilds and would drop them).
func TestScopedRenderMergesLock(t *testing.T) {
	repo(t)
	fixture := guidesFixture(t)
	write(t, ".claude/fragments/AGENTS.md/layout.toml", "fragments = [\"cc-skills:ccx\"]\n"+ccSkillsSource)
	write(t, ".claude/fragments/CLAUDE.md/layout.toml", "fragments = [\"cc-skills:ccx\"]\n"+ccSkillsSource)
	if code, _, errout := exec("render", "--source", srcFlag(fixture)); code != 0 {
		t.Fatalf("full render: code=%d err=%s", code, errout)
	}
	lock, _ := os.ReadFile(".claude/fragments/cc-guides.lock")
	if !strings.Contains(string(lock), `"AGENTS.md"`) || !strings.Contains(string(lock), `"CLAUDE.md"`) {
		t.Fatalf("full render must register both:\n%s", lock)
	}
	if code, _, errout := exec("render", ".claude/fragments/AGENTS.md", "--source", srcFlag(fixture)); code != 0 {
		t.Fatalf("scoped render: code=%d err=%s", code, errout)
	}
	lock2, _ := os.ReadFile(".claude/fragments/cc-guides.lock")
	if !strings.Contains(string(lock2), `"CLAUDE.md"`) {
		t.Fatalf("scoped render must preserve the untouched artifact in the lock:\n%s", lock2)
	}
}


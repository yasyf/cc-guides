// srcFlag builds the --source override for the local guides fixture.
func srcFlag(fixture string) string { return "cc-skills=" + fixture }

// ccSkillsSource is the [sources.cc-skills] table a layout that imports cc-skills
// must declare (there is no baked default); --source overrides its spec to the
// local fixture so tests stay offline.
const ccSkillsSource = "\n[sources.cc-skills]\nsource = \"github:yasyf/cc-skills@main\"\n"

// mdMarker/shMarker are the version-free generated markers a v3 render writes.
func mdMarker(dir string) string {
	return "<!-- GENERATED by cc-guides from " + dir + "/ — do not edit; edit the fragments and push — CI renders. -->"
}

func shMarker(dir string) string {
	return "# GENERATED by cc-guides from " + dir + "/ — do not edit; edit the fragments and push — CI renders."
}

// ymlMarker is the yaml artifact's marker — the shell `# ` comment form.
func ymlMarker(dir string) string { return shMarker(dir) }

